export const AMERICAN_CLIMATES: readonly Climate[] = [
  "andean",
  "prairie",
  "mesoamerican",
];

export const FRONTIER_CLIMATES: readonly Climate[] = [
  "tundra",
  "temperate-rainforest",
  "equatorial-wetlands",
];

const NEW_CLIMATES: Climate[] = ["oceanic", "alpine", "subtropical", "savanna"];
export const EXTREME_CLIMATES: readonly Climate[] = [
  "glacial",
  "hyperarid",
  "monsoon",
];
/** Extremes remain possible starting regions, with lower relative frequency. */
export function climateInitialWeight(climate: Climate): number {
  return EXTREME_CLIMATES.includes(climate) ? 0.35 : 1;
}
const TRANSITION_WEIGHTS: Partial<
  Record<Climate, Partial<Record<Climate, number>>>
> = {
  tundra: { arctic: 2 },
  "temperate-rainforest": { oceanic: 2 },
  "equatorial-wetlands": { tropical: 2 },
  temperate: { cold: 1.5 },
  steppe: { cold: 1.5 },
  mediterranean: { desert: 0.5, steppe: 0.5 },
  tropical: { desert: 2 },
  desert: { tropical: 2 },
  cold: { arctic: 2 },
  oceanic: { temperate: 2 },
  alpine: { cold: 2, arctic: 2 },
  subtropical: { tropical: 2 },
  savanna: { tropical: 2 },
  glacial: { arctic: 2, alpine: 1 },
  hyperarid: { desert: 2 },
  monsoon: { tropical: 2, subtropical: 1, savanna: 1 },
  andean: { alpine: 2 },
  prairie: { steppe: 2 },
  mesoamerican: { subtropical: 2 },
};
/** Relative destination weights, after checking immediate-neighbor compatibility. */
export function climateTransitionWeight(from: Climate, to: Climate): number {
  if (from === to) return 1;
  if (FRONTIER_CLIMATES.includes(to)) return 0.75;
  if (FRONTIER_CLIMATES.includes(from))
    return TRANSITION_WEIGHTS[from]?.[to] ?? 1;
  if (AMERICAN_CLIMATES.includes(to))
    return AMERICAN_CLIMATES.includes(from) ? 1 : 0.75;
  if (AMERICAN_CLIMATES.includes(from))
    return TRANSITION_WEIGHTS[from]?.[to] ?? 1;
  return (
    TRANSITION_WEIGHTS[from]?.[to] ??
    (EXTREME_CLIMATES.includes(to)
      ? 0.5
      : !NEW_CLIMATES.includes(from) && NEW_CLIMATES.includes(to)
        ? 0.5
        : 1)
  );
}
export function compatibleClimate(a: Climate, b: Climate) {
  return (
    a === b ||
    (CLIMATE_INFO[a].compatible.includes(b) &&
      CLIMATE_INFO[b].compatible.includes(a))
  );
}
export function waterProbabilities(
  climate: Climate,
  openWater = false,
): [Biome, number][] {
  let remaining = 1;
  const result: [Biome, number][] = CLIMATE_INFO[climate].water.map(
    ([biome, chance]) => {
      chance = Math.min(1, chance * (openWater && biome === "whale" ? 2 : 1));
      const value = remaining * chance;
      remaining *= 1 - chance;
      return [biome, value];
    },
  );
  return [...result, ["water", remaining]];
}
